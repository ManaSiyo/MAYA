import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { evaluateProxyPolicy } from '../docs/server/proxy-policy.mjs';

const source=readFileSync(new URL('../backend/operations.html',import.meta.url),'utf8');
const start=source.indexOf('function resolveType(t){');
const end=source.indexOf('\nfunction buildQuery(',start);
assert(start>=0 && end>start);
const requests=[];
let response={answers:[{type:'choice',name:'pattern_category',choice:'pants',confidence:0.95}]};
const KB={grammar:{types:{pants:{match:['pants'],summary:'Two leg panels'},jacket:{match:['jacket'],summary:'Outer garment'}}}};
const context=vm.createContext({KB, AbortController, setTimeout, clearTimeout, getKey:()=> 'token',
  fetch:async (url,opts)=>{requests.push({url,...opts});return {ok:true,json:async()=>response};}});
vm.runInContext(source.slice(start,end),context);
assert.equal(context.resolveType(''), 'unknown');
assert.equal(context.resolveType('pants'), 'pants');
assert.equal(await context.decidePatternCategory({type:'track bottoms',subtype:'athletic'},'track bottoms'),'pants');
const sent=JSON.parse(requests[0].body);
assert.equal(requests[0].url,'/api/openai/v1/decisions');
assert.equal(sent.prompt_cache_options.mode,'explicit');
assert(!requests[0].body.includes('photo'));
response={answers:[{type:'choice',name:'pattern_category',choice:'pants',confidence:0.4}]};
assert.equal(await context.decidePatternCategory({type:'ambiguous'},'ambiguous'),'ambiguous');
response={answers:[{type:'refusal',name:'pattern_category'}]};
assert.equal(await context.decidePatternCategory({type:'ambiguous'},'ambiguous'),'ambiguous');
response={answers:[{type:'choice',name:'pattern_category',choice:'unknown',confidence:1}]};
assert.equal(await context.decidePatternCategory({type:'ambiguous'},'ambiguous'),'ambiguous');
context.fetch=async()=>{throw Error('offline');};
assert.equal(await context.decidePatternCategory({type:'ambiguous'},'ambiguous'),'ambiguous');
const ev=(body,isAdmin=true)=>evaluateProxyPolicy({method:'POST',upstreamPath:'v1/decisions',contentType:'application/json',body:Buffer.from(JSON.stringify(body)),isAdmin,models:{}});
assert(ev(sent).ok);
assert(!ev(sent,false).ok);
assert(!ev({...sent,model:'gpt-6-astra'}).ok);
assert(!ev({...sent,input:'x'.repeat(1001)}).ok);
assert(!ev({...sent,input:[{type:'input_image'}]}).ok);
assert(!ev({...sent,prompt_cache_options:{mode:'automatic'}}).ok);
assert(source.includes('const hits = retrieve(qvec, retrievalType, 5)'));
assert(source.includes('const grammar = KB.grammar.types[typeKey]'));
console.log('pattern decisions: bounded routing, fallback and proxy policy passed');
